<?php

namespace App\Http\Requests;

use Illuminate\Contracts\Validation\ValidationRule;
use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Validation\Rule;

class FormShareLinkRequest extends FormRequest
{
    /**
     * Aliases that would collide with reserved application URL segments.
     *
     * @var list<string>
     */
    public const RESERVED_ALIASES = [
        'auth',
        'admin',
        'dashboard',
        'joined',
        'api',
        's',
    ];

    public function authorize(): bool
    {
        return true;
    }

    /**
     * Validate a requested alias while allowing an empty value to select one
     * generated by the share-link service.
     *
     * @return array<string, list<ValidationRule|string>>
     */
    public function rules(): array
    {
        $rules = [
            'nullable',
            'string',
            'max:50',
        ];

        if (filled($this->input('alias'))) {
            $rules[] = 'min:3';
            $rules[] = 'regex:/\A[a-z0-9-]+\z/';
            $rules[] = Rule::notIn(self::RESERVED_ALIASES);
        }

        return ['alias' => $rules];
    }
}
